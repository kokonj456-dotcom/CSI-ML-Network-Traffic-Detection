class ExperimentRequest(BaseModel):
    name: str = Field(default="Autoencoder experiment", min_length=1, max_length=120)
    threshold_percentile: float = Field(default=95.0, ge=50.0, le=99.9)
    mode: Literal["existing", "retrain"] = "existing"
    epochs: int = Field(default=20, ge=1, le=100)
    batch_size: int = Field(default=256, ge=16, le=4096)
    learning_rate: float = Field(default=0.001, gt=0, le=0.1)
    dataset: Literal["KDDTest", "KDDTest-21"] = "KDDTest"


def read_run(run_id):
    # Prevent path traversal: only allow IDs generated by this app.
    if not run_id or any(ch not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_-" for ch in run_id):
        return None
    path = RUNS_DIR / run_id / "experiment.json"
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def write_run(run_id, item):
    run_dir = RUNS_DIR / run_id
    run_dir.mkdir(parents=True, exist_ok=True)
    (run_dir / "experiment.json").write_text(
        json.dumps(item, ensure_ascii=False, indent=2, default=str), encoding="utf-8"
    )


def read_csv_pair(name: str):
    features_path = DATA_DIR / f"{name}_features.csv"
    targets_path = DATA_DIR / f"{name}_targets.csv"
    if not features_path.exists() or not targets_path.exists():
        missing = [str(p) for p in [features_path, targets_path] if not p.exists()]
        raise FileNotFoundError(
            "ไม่พบไฟล์ชุดข้อมูลที่จำเป็น: " + ", ".join(missing)
            + ". โปรดวาง data-pipeline/output/NSL-KDD/feature_engineered ไว้ที่ root ของโปรเจกต์"
        )
    features = pd.read_csv(features_path)
    targets = pd.read_csv(targets_path)
    if len(features) != len(targets):
        raise ValueError(f"{name}: จำนวนแถว features และ targets ไม่ตรงกัน")
    return features, targets


def load_existing_model():
    for p in [MODEL_PATH, SCALER_PATH, FEATURES_PATH]:
        if not p.exists():
            raise FileNotFoundError(f"ไม่พบไฟล์โมเดลที่จำเป็น: {p}")
    scaler = joblib.load(SCALER_PATH)
    feature_columns = FEATURES_PATH.read_text(encoding="utf-8").splitlines()
    model = Autoencoder(input_dim=len(feature_columns))
    try:
        state = torch.load(MODEL_PATH, map_location="cpu", weights_only=True)
    except TypeError:
        state = torch.load(MODEL_PATH, map_location="cpu")
    model.load_state_dict(state)
    model.eval()
    return model, scaler, feature_columns


def train_new_model(epochs: int, batch_size: int, learning_rate: float):
    features, targets = read_csv_pair("KDDTrain")
    normal_mask = targets["is_attack"].eq(0)
    normal_features = features.loc[normal_mask].copy()
    x_train, x_val = train_test_split(
        normal_features, test_size=0.20, random_state=42, shuffle=True
    )
    constant_columns = x_train.columns[x_train.nunique() <= 1]
    x_train = x_train.drop(columns=constant_columns)
    x_val = x_val.drop(columns=constant_columns)
    feature_columns = list(x_train.columns)

    scaler = StandardScaler()
    x_train_scaled = scaler.fit_transform(x_train)
    x_val_scaled = scaler.transform(x_val)

    train_tensor = torch.tensor(x_train_scaled, dtype=torch.float32)
    val_tensor = torch.tensor(x_val_scaled, dtype=torch.float32)
    loader = torch.utils.data.DataLoader(
        torch.utils.data.TensorDataset(train_tensor),
        batch_size=batch_size,
        shuffle=True,
    )
    model = Autoencoder(input_dim=len(feature_columns))
    optimizer = torch.optim.Adam(model.parameters(), lr=learning_rate)
    criterion = torch.nn.MSELoss()
    history = []

    for epoch in range(epochs):
        model.train()
        total = 0.0
        for (batch,) in loader:
            optimizer.zero_grad()
            reconstructed = model(batch)
            loss = criterion(reconstructed, batch)
            loss.backward()
            optimizer.step()
            total += loss.item() * len(batch)
        train_loss = total / len(train_tensor)

        model.eval()
        with torch.no_grad():
            reconstructed_val = model(val_tensor)
            val_loss = criterion(reconstructed_val, val_tensor).item()
        history.append({
            "epoch": epoch + 1,
            "train_loss": round(float(train_loss), 8),
            "validation_loss": round(float(val_loss), 8),
        })

    model.eval()
    return model, scaler, feature_columns, history


def reconstruction_errors(model, scaler, feature_columns, frame, batch_size=4096):
    missing = sorted(set(feature_columns) - set(frame.columns))
    if missing:
        raise ValueError(f"ข้อมูลไม่มีฟีเจอร์ที่โมเดลต้องใช้: {missing[:20]}")
    matrix = scaler.transform(frame[feature_columns])
    tensor = torch.tensor(matrix, dtype=torch.float32)
    chunks = []
    model.eval()
    with torch.no_grad():
        for start in range(0, len(tensor), batch_size):
            batch = tensor[start:start + batch_size]
            reconstructed = model(batch)
            errors = ((batch - reconstructed) ** 2).mean(dim=1)
            chunks.extend(errors.cpu().numpy().tolist())
    return np.asarray(chunks, dtype=float)


def save_chart_data(run_dir: Path, y_true, predictions, details: pd.DataFrame, threshold: float):
    tn, fp, fn, tp = confusion_matrix(y_true, predictions, labels=[0, 1]).ravel()
    # Save chart-friendly JSON and portable CSV reports.
    matrix = {"labels": ["Normal", "Attack"], "matrix": [[int(tn), int(fp)], [int(fn), int(tp)]]}
    (run_dir / "confusion_matrix.json").write_text(json.dumps(matrix, ensure_ascii=False), encoding="utf-8")

    attack = details.loc[details["is_attack"] == 1].copy()
    if "label" in attack.columns:
        grouped = attack.groupby("label", dropna=False).agg(
            total=("predicted_attack", "size"),
            detected=("predicted_attack", "sum"),
        ).reset_index()
        grouped["detection_rate"] = grouped["detected"] / grouped["total"]
        grouped = grouped.sort_values(["detection_rate", "total"], ascending=[True, False])
        grouped.to_csv(run_dir / "detection_by_attack.csv", index=False, encoding="utf-8-sig")
        labels = grouped["label"].astype(str).tolist()
        rates = grouped["detection_rate"].astype(float).round(6).tolist()
    else:
        labels, rates = [], []
    (run_dir / "detection_by_attack.json").write_text(
        json.dumps({"labels": labels, "rates": rates}, ensure_ascii=False), encoding="utf-8"
    )
    details.to_csv(run_dir / "record_details.csv", index=False, encoding="utf-8-sig")
    return matrix, {"labels": labels, "rates": rates}



def save_run_plots(run_dir: Path, history, y_true, predictions, test_errors, threshold):
    """บันทึกกราฟ PNG ของแต่ละรอบไว้ใน backup/<run_id>/plots/"""
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        plots_dir = run_dir / "plots"
        plots_dir.mkdir(parents=True, exist_ok=True)

        if history:
            epochs = [row["epoch"] for row in history]
            fig, ax = plt.subplots(figsize=(8, 5))
            ax.plot(epochs, [row["train_loss"] for row in history], label="Training Loss")
            ax.plot(epochs, [row["validation_loss"] for row in history], label="Validation Loss")
            ax.set_title("Autoencoder Training Curves")
            ax.set_xlabel("Epoch")
            ax.set_ylabel("MSE Loss")
            ax.grid(True, alpha=0.25)
            ax.legend()
            fig.tight_layout()
            fig.savefig(plots_dir / "training_curves.png", dpi=140)
            plt.close(fig)

        cm = confusion_matrix(y_true, predictions, labels=[0, 1])
        fig, ax = plt.subplots(figsize=(6, 5))
        image = ax.imshow(cm, interpolation="nearest")
        ax.set_title("Confusion Matrix")
        ax.set_xlabel("Predicted")
        ax.set_ylabel("Actual")
        ax.set_xticks([0, 1], ["Normal", "Attack"])
        ax.set_yticks([0, 1], ["Normal", "Attack"])
        for (i, j), value in np.ndenumerate(cm):
            ax.text(j, i, str(int(value)), ha="center", va="center")
        fig.colorbar(image, ax=ax)
        fig.tight_layout()
        fig.savefig(plots_dir / "confusion_matrix.png", dpi=140)
        plt.close(fig)

        fig, ax = plt.subplots(figsize=(8, 5))
        ax.hist(np.asarray(test_errors)[np.asarray(y_true) == 0], bins=60, alpha=0.65, label="Normal")
        ax.hist(np.asarray(test_errors)[np.asarray(y_true) == 1], bins=60, alpha=0.55, label="Attack")
        ax.axvline(threshold, linestyle="--", label=f"Threshold = {threshold:.5g}")
        ax.set_title("Reconstruction Error Distribution")
        ax.set_xlabel("Reconstruction Error")
        ax.set_ylabel("Number of records")
        ax.legend()
        ax.grid(True, alpha=0.2)
        fig.tight_layout()
        fig.savefig(plots_dir / "reconstruction_error_distribution.png", dpi=140)
        plt.close(fig)
    except ImportError:
        # JSON and CSV results remain available even if matplotlib is not installed.
        return

