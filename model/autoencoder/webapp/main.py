@app.post("/api/experiments")
def create_experiment(req: ExperimentRequest):
    experiment_id = "AE_" + datetime.now().strftime("%Y%m%d_%H%M%S") + "_" + uuid.uuid4().hex[:6]
    created_at = datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds")
    run_dir = RUNS_DIR / experiment_id
    run_dir.mkdir(parents=True, exist_ok=True)
    config_dict = req.model_dump() if hasattr(req, "model_dump") else req.dict()

    item = {
        "id": experiment_id, "name": req.name, "created_at": created_at,
        "status": "running", "config": config_dict, "metrics": None,
        "artifacts": None, "error": ""
    }
    write_run(experiment_id, item)
    started_clock = __import__("time").perf_counter()
    try:
        train_features, train_targets = read_csv_pair("KDDTrain")
        test_features, test_targets = read_csv_pair(req.dataset)

        if req.mode == "retrain":
            model, scaler, feature_columns, history = train_new_model(
                req.epochs, req.batch_size, req.learning_rate
            )
            pd.DataFrame(history).to_csv(run_dir / "training_history.csv", index=False, encoding="utf-8-sig")
            # Save a versioned model per experiment; do not overwrite the current production model.
            torch.save(model.state_dict(), run_dir / "autoencoder.pth")
            joblib.dump(scaler, run_dir / "scaler.pkl")
            (run_dir / "feature_columns.txt").write_text("\n".join(feature_columns), encoding="utf-8")
        else:
            model, scaler, feature_columns = load_existing_model()
            history = []

        normal_mask = train_targets["is_attack"].eq(0)
        normal_features = train_features.loc[normal_mask]
        _, validation = train_test_split(
            normal_features, test_size=0.20, random_state=42, shuffle=True
        )
        validation_errors = reconstruction_errors(model, scaler, feature_columns, validation)
        threshold = float(np.percentile(validation_errors, req.threshold_percentile))

        test_errors = reconstruction_errors(model, scaler, feature_columns, test_features)
        predictions = (test_errors > threshold).astype(int)
        y_true = test_targets["is_attack"].astype(int).to_numpy()
        tn, fp, fn, tp = confusion_matrix(y_true, predictions, labels=[0, 1]).ravel()
        metrics = {
            "duration_seconds": round(__import__("time").perf_counter() - started_clock, 2),
            "total_records": int(len(y_true)),
            "threshold": threshold,
            "threshold_percentile": req.threshold_percentile,
            "accuracy": float(accuracy_score(y_true, predictions)),
            "precision": float(precision_score(y_true, predictions, zero_division=0)),
            "recall": float(recall_score(y_true, predictions, zero_division=0)),
            "f1": float(f1_score(y_true, predictions, zero_division=0)),
            "false_positive_rate": float(fp / (fp + tn)) if (fp + tn) else 0.0,
            "tn": int(tn), "fp": int(fp), "fn": int(fn), "tp": int(tp),
            "normal_count": int((y_true == 0).sum()),
            "attack_count": int((y_true == 1).sum()),
            "detected_attacks": int(tp),
            "missed_attacks": int(fn),
            "feature_count": int(len(feature_columns)),
            "training_history": history,
        }
        details = test_targets.copy()
        details["is_attack"] = y_true
        details["predicted_attack"] = predictions
        details["reconstruction_error"] = test_errors
        details["threshold"] = threshold
        details["result"] = np.where(predictions == 1, "Attack detected", "Predicted normal")
        matrix, attack_chart = save_chart_data(run_dir, y_true, predictions, details, threshold)
        save_run_plots(run_dir, history, y_true, predictions, test_errors, threshold)
        artifact = {
            "run_dir": str(run_dir),
            "confusion_matrix": f"/api/experiments/{experiment_id}/files/confusion_matrix.json",
            "detection_by_attack": f"/api/experiments/{experiment_id}/files/detection_by_attack.json",
            "record_details": f"/api/experiments/{experiment_id}/files/record_details.csv",
            "training_history": f"/api/experiments/{experiment_id}/files/training_history.csv" if history else None,
            "plots_directory": str(run_dir / "plots"),
        }
        (run_dir / "config.json").write_text(json.dumps(config_dict, ensure_ascii=False, indent=2), encoding="utf-8")
        (run_dir / "metrics.json").write_text(json.dumps(metrics, ensure_ascii=False, indent=2), encoding="utf-8")
        item.update({
            "status": "completed", "metrics": metrics,
            "confusion_matrix": matrix, "detection_by_attack": attack_chart,
            "artifacts": artifact, "error": ""
        })
        write_run(experiment_id, item)
        return item
    except Exception as exc:
        error = str(exc)
        item.update({"status": "failed", "error": error, "error_trace": traceback.format_exc(limit=8)})
        write_run(experiment_id, item)
        raise HTTPException(status_code=400, detail=error)


@app.get("/api/experiments")
def list_experiments():
    results = []
    if RUNS_DIR.exists():
        for folder in RUNS_DIR.iterdir():
            if folder.is_dir():
                item = read_run(folder.name)
                if item:
                    results.append(item)
    results.sort(key=lambda item: item.get("created_at", ""), reverse=True)
    return results


@app.get("/api/experiments/{experiment_id}")
def get_experiment(experiment_id: str):
    item = read_run(experiment_id)
    if not item:
        raise HTTPException(status_code=404, detail="ไม่พบรายการทดลอง")
    return item


@app.get("/api/experiments/{experiment_id}/files/{filename}")
def get_artifact(experiment_id: str, filename: str):
    allowed = {
        "confusion_matrix.json", "detection_by_attack.json",
        "record_details.csv", "detection_by_attack.csv",
        "training_history.csv", "autoencoder.pth", "scaler.pkl",
        "feature_columns.txt", "plots/confusion_matrix.png",
        "plots/reconstruction_error_distribution.png", "plots/training_curves.png",
    }
    if filename not in allowed:
        raise HTTPException(status_code=400, detail="ไฟล์นี้ไม่อนุญาตให้ดาวน์โหลด")
    if not experiment_id or any(ch not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_-" for ch in experiment_id):
        raise HTTPException(status_code=400, detail="รหัสการทดลองไม่ถูกต้อง")
    path = RUNS_DIR / experiment_id / filename
    if not path.exists():
        raise HTTPException(status_code=404, detail="ไม่พบไฟล์ผลลัพธ์")
    return FileResponse(path, filename=filename)


